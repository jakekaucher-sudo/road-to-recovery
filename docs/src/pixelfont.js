const GLYPHS = {};
for (const k in RAW) {
  const rows = RAW[k].split("|");
  let minc = 5, maxc = -1;
  rows.forEach(r => { for (let c = 0; c < 5; c++) if (r[c] === "#") { if (c < minc) minc = c; if (c > maxc) maxc = c; } });
  if (maxc < 0) { minc = 0; maxc = 2; }
  GLYPHS[k] = { rows, x0: minc, w: maxc - minc + 1 };
}
GLYPHS[" "] = { rows: [], x0: 0, w: 3 };

export function pixelWidth(s, px, spacing = 1) {
  s = String(s).toUpperCase(); let w = 0;
  for (const ch of s) { const g = GLYPHS[ch] || GLYPHS["?"]; w += (g.w + spacing) * px; }
  return w - spacing * px;
}
const cache = new Map();
function renderRun(s, px, color) {
  const key = s + "|" + px + "|" + color;
  let c = cache.get(key);
  if (c) return c;
  const w = Math.ceil(pixelWidth(s, px)) + 2, h = 7 * px + 2;
  c = document.createElement("canvas"); c.width = Math.max(1, w); c.height = h;
  const g = c.getContext("2d"); g.fillStyle = color;
  let x = 1;
  for (const ch of s) {
    const gl = GLYPHS[ch] || GLYPHS["?"];
    for (let r = 0; r < gl.rows.length; r++) {
      const row = gl.rows[r];
      for (let col = gl.x0; col < gl.x0 + gl.w; col++) if (row[col] === "#") g.fillRect(x + (col - gl.x0) * px, 1 + r * px, px, px);
    }
    x += (gl.w + 1) * px;
  }
  if (cache.size > 400) cache.clear();
  cache.set(key, c);
  return c;
}
// Draw pixel text. align: left|center|right. Optional shadow / outline colors.
export function pixelText(ctx, s, x, y, px, color, opts = {}) {
  s = String(s).toUpperCase();
  const run = renderRun(s, px, color);
  const w = run.width - 2;
  let dx = x;
  if (opts.align === "center") dx = x - w / 2; else if (opts.align === "right") dx = x - w;
  dx = Math.round(dx); y = Math.round(y);
  if (opts.outline) { const o = renderRun(s, px, opts.outline); const k = Math.max(1, Math.round(px * 0.5)); for (let i = -k; i <= k; i += k) for (let j = -k; j <= k; j += k) if (i || j) ctx.drawImage(o, dx - 1 + i, y - 1 + j); }
  if (opts.shadow) { const sh = renderRun(s, px, opts.shadow); ctx.drawImage(sh, dx - 1 + px, y - 1 + px); }
  if (opts.alpha !== undefined) { const a = ctx.globalAlpha; ctx.globalAlpha = a * opts.alpha; ctx.drawImage(run, dx - 1, y - 1); ctx.globalAlpha = a; }
  else ctx.drawImage(run, dx - 1, y - 1);
  return w;
}
